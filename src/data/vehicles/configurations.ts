import type { Configuration, Spec, Verification } from "@/types/vehicle";

/**
 * US-market configurations. Values are `null` when Tesla does not publish them
 * (e.g. battery capacity, horsepower for most Model 3/Y trims) — they are never estimated.
 *
 * Verification (2026-11-07):
 *  - EPA range and consumption: fueleconomy.gov web-services API → "regulatory", per-record source.
 *  - 0–60, top speed, peak power, cargo, peak DC: tesla.com product pages (read in a browser) →
 *    "manufacturer". Where tesla.com and EPA disagree on range, EPA is shown and Tesla's figure is noted.
 *  - Anything still "secondary" was not shown on tesla.com (e.g. most top speeds, MSRP — tesla.com
 *    shows lease/finance offers rather than a stable cash price).
 *  - Next-gen Roadster figures are 2017 announcement targets → "announced-target".
 */
function s(value: number | null, verification: Verification, sourceIds: string[], note?: string): Spec {
  return note ? { value, verification, sourceIds, note } : { value, verification, sourceIds };
}

