import { chromium } from "@playwright/test";
const base = process.argv[2];
const browser = await chromium.launch({ args: ["--use-angle=swiftshader", "--enable-unsafe-swiftshader", "--ignore-gpu-blocklist"] });
const page = await browser.newPage({ viewport: { width: 1100, height: 700 } });
const msgs = [];
page.on("console", (m) => { if (m.type() === "error" || m.type() === "warning") msgs.push(`[${m.type()}] ${m.text().slice(0, 220)}`); });
page.on("pageerror", (e) => msgs.push("PAGEERROR " + e.message.slice(0, 220)));
const step = async (label, fn) => { const n = msgs.length; try { await fn(); } catch (e) { console.log(`${label}: FAILED ${e.message.split("\n")[0]}`); } await page.waitForTimeout(4000); console.log(`${label}: ${msgs.length - n} new`, msgs.slice(n).map((m) => m.slice(0, 160))); };
await page.goto(base + "/?q=high"); await page.waitForTimeout(15000);
await step("hero switch Model X", () => page.getByRole("radio", { name: "Model X" }).click());
await step("hero switch Roadster", () => page.getByRole("radio", { name: "Roadster" }).click());
await step("nav → studio", () => page.getByRole("link", { name: "3D Studio" }).first().click());
for (const n of ["Doors", "Frunk", "Trunk", "Night", "Components", "Turntable"]) await step(`toggle ${n}`, () => page.getByRole("switch", { name: n }).click());
for (const n of ["X-ray", "Wire", "Interior", "Top", "Solid"]) await step(`radio ${n}`, () => page.getByRole("radio", { name: n }).first().click());
await step("studio → Roadster", () => page.getByRole("link", { name: "Roadster" }).last().click());
await step("roadster gen switch", () => page.getByRole("radio", { name: /1st generation/ }).click({ timeout: 15000 }));
await step("nav → engineering", () => page.getByRole("link", { name: "Engineering" }).first().click());
for (const n of ["Battery", "Motors"]) await step(`select ${n}`, () => page.getByRole("button", { name: new RegExp(`${n}$`) }).first().click({ timeout: 15000 }));
await step("flow accelerate", () => page.getByRole("radio", { name: "Accelerate" }).click());
await step("exploded", () => page.getByRole("button", { name: /Exploded view/ }).click());
await step("vehicle → Model X", () => page.locator("#eng-vehicle").selectOption("model-x"));
await step("nav → compare", () => page.getByRole("link", { name: "Compare" }).first().click());
await step("compare side view", () => page.getByRole("radio", { name: "Side" }).click());
await step("nav → vehicles/model-s", () => page.goto(base + "/vehicles/model-s?q=high"));
await step("config tab Plaid", () => page.getByRole("tab", { name: /Plaid/ }).click());
await step("nav → home", () => page.getByRole("link", { name: "TeslHa home" }).click());
console.log("\n" + [...new Set(msgs)].join("\n"));
await browser.close();
